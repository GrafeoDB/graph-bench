"""The full overview page, `docs/results.md`: every database's version, source, machine and run date, the runs
behind the sources, then every per-case table.

The README's results section and the summary block in grafeo's README link to it. The tables are those of the
README section (`render_readme`): with a local snapshot merged in (`graph-bench merge --local`), its databases
follow the CI ones, marked `†`, and nothing is budgeted or ranked across the two sources.
"""

from graph_bench.report.ranking import LOCAL_MARK, all_databases, column_name, database_source, local_databases
from graph_bench.report.readme import render_readme, version_text
from graph_bench.report.summary import grafeo_text, machine_text
from graph_bench.results import Results
from graph_bench.types import SOURCES

TITLE = "# graph-bench: full results"
SOURCE_NAMES = {"ci": "CI", "local": "local snapshot"}
INTRO = (
    "Generated by `graph-bench report --format overview` from the results behind the README's results section;"
    " do not edit by hand."
)
LOCAL_INTRO = (
    f"CI measures Grafeo against a fixed roster on its reference runner. A database marked {LOCAL_MARK} comes from"
    " the local snapshot, a run of all ten on the dev box (CONTRIBUTING.md), and is never budgeted or ranked"
    " against the CI ones."
)


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def _source_name(source: str) -> str:
    return SOURCE_NAMES.get(source, source)


def _used_sources(results: Results) -> list[str]:
    used = {database_source(results, db) for db in all_databases(results)} or {"ci"}
    return [s for s in SOURCES if s in used] + sorted(used - set(SOURCES))


def render_overview(results: Results) -> str:
    """The whole page: the databases table, the runs table, then the README section's tables."""
    rows = []
    for db in all_databases(results):
        source = database_source(results, db)
        run = results.run(source)
        info = results.databases.get(db)
        version = version_text(info) if info is not None else ""
        rows.append(
            [
                column_name(results, db),
                version,
                _source_name(source),
                machine_text(run["machine"]),
                run["started_at"][:10],
            ]
        )
    runs = []
    for source in _used_sources(results):
        run = results.run(source)
        runs.append(
            [
                _source_name(source),
                machine_text(run["machine"]),
                run["started_at"][:10],
                run["graph_bench_commit"][:7],
                grafeo_text(run["grafeo"]),
                run["selection"],
                run["mode"],
            ]
        )
    intro = INTRO + (" " + LOCAL_INTRO if local_databases(results) else "")
    lines = [TITLE, "", intro, "", "## Databases", ""]
    lines += _table(["Database", "Version", "Source", "Machine", "Run date"], rows)
    lines += ["", "## Runs", ""]
    lines += _table(["Source", "Machine", "Run date", "graph-bench", "Grafeo", "Selection", "Mode"], runs)
    lines += ["", "## Results", "", render_readme(results, overview_link=None).rstrip("\n")]
    return "\n".join(lines) + "\n"


__all__ = ["render_overview"]
